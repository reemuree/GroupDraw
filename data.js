const DEFAULT_DATA = {
  version: APP_VERSION,
  students: [...DEMO_STUDENTS],
  topics: [],
  sessions: [],
  settings: { ...DEFAULT_SETTINGS },
};

/**
 * Load application state from LocalStorage.
 * Returns a validated data object; never throws for missing/corrupt data.
 */
function loadData() {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return structuredClone(DEFAULT_DATA);

    const parsed = JSON.parse(raw);
    if (!parsed || typeof parsed !== 'object') return structuredClone(DEFAULT_DATA);

    return {
      version: parsed.version || APP_VERSION,
      students: Array.isArray(parsed.students) ? parsed.students : [...DEMO_STUDENTS],
      topics: Array.isArray(parsed.topics) ? parsed.topics : [],
      sessions: Array.isArray(parsed.sessions) ? parsed.sessions : [],
      settings: { ...DEFAULT_SETTINGS, ...(parsed.settings || {}) },
    };
  } catch (e) {
    console.warn('GroupDraw: failed to load data, using defaults', e);
    return structuredClone(DEFAULT_DATA);
  }
}

/**
 * Persist application state.
 */
function saveData(data) {
  try {
    data.version = APP_VERSION;
    localStorage.setItem(STORAGE_KEY, JSON.stringify(data));
    return true;
  } catch (e) {
    console.error('GroupDraw: failed to save data', e);
    return false;
  }
}

/**
 * Generate a short unique ID.
 */
function generateId(prefix = 'id') {
  return `${prefix}_${Date.now().toString(36)}_${Math.random().toString(36).slice(2, 8)}`;
}

/**
 * Fisher–Yates shuffle (in-place). Uses Math.random() for classroom fairness.
 * Not cryptographically secure — documented intentionally.
 */
function fisherYatesShuffle(array) {
  const arr = array.slice();
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

/**
 * Group a shuffled list of students according to size and leftover policy.
 * Policies: 'smaller' | 'even' | 'unassigned'
 */
function createGroups(students, groupSize, leftoverPolicy) {
  const n = students.length;
  if (n === 0 || groupSize < 1) return { groups: [], unassigned: [] };

  let groups = [];
  let unassigned = [];

  if (leftoverPolicy === 'even') {
    // Distribute as evenly as possible
    const numGroups = Math.max(1, Math.ceil(n / groupSize));
    const base = Math.floor(n / numGroups);
    const extra = n % numGroups;
    let idx = 0;
    for (let g = 0; g < numGroups; g++) {
      const size = base + (g < extra ? 1 : 0);
      groups.push(students.slice(idx, idx + size));
      idx += size;
    }
  } else if (leftoverPolicy === 'unassigned') {
    const full = Math.floor(n / groupSize);
    for (let g = 0; g < full; g++) {
      groups.push(students.slice(g * groupSize, (g + 1) * groupSize));
    }
    unassigned = students.slice(full * groupSize);
  } else {
    // 'smaller' — allow a final smaller group
    let idx = 0;
    while (idx < n) {
      groups.push(students.slice(idx, idx + groupSize));
      idx += groupSize;
    }
  }

  return { groups, unassigned };
}

/**
 * Assign topics to groups.
 * mode: 'same' | 'different'
 */
function assignTopics(groups, topics, mode) {
  if (!topics || topics.length === 0) {
    return groups.map((members, i) => ({
      groupNumber: i + 1,
      groupName: `Group ${i + 1}`,
      topic: null,
      members,
    }));
  }

  if (mode === 'same') {
    const topic = topics[0];
    return groups.map((members, i) => ({
      groupNumber: i + 1,
      groupName: `Group ${i + 1}`,
      topic,
      members,
    }));
  }

  // different — cycle through topics
  return groups.map((members, i) => ({
    groupNumber: i + 1,
    groupName: `Group ${i + 1}`,
    topic: topics[i % topics.length],
    members,
  }));
}

/**
 * Escape HTML to prevent XSS when inserting user content.
 */
function escapeHtml(str) {
  if (str == null) return '';
  const div = document.createElement('div');
  div.textContent = String(str);
  return div.innerHTML;
}

/**
 * Format date/time for display.
 */
function formatDateTime(iso) {
  try {
    const d = new Date(iso);
    return d.toLocaleString(undefined, {
      year: 'numeric',
      month: 'short',
      day: 'numeric',
      hour: '2-digit',
      minute: '2-digit',
    });
  } catch {
    return iso;
  }
}